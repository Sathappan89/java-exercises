package MethodAssignments;

/*Define a method that returns the product of two double numbers*/
public class productTwoNumber {

	public static void prod(double a, double b) {
		System.out.println("Product One " + a);
		System.out.println("Product Two " + b);
	}

	public static void main(String[] args) {

		prod(10.0, 20.0);
		productTwoNumber.prod(3.0, 5.0);
	}

}
