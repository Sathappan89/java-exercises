package JavaInheritanceConcept;

public class vehicle {
	

	public void loading() {
		System.out.println("vehicle----loading");
	}
	
	public void indiaVehicle() {
		System.out.println("vehicle----india");
	}
	
	public final void ff() {
		System.out.println("vehicle----ff");
	}
	
	public static void ss() {
		System.out.println("vehicle----static");
	}
}
